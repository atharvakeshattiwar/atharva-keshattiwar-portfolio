// Fuzzy match — finds the closest keyword even with typos or partial matches
function fuzzyMatch(input, keyword) {
  if (input.includes(keyword)) return 1
  const words = input.split(/\s+/)
  for (const word of words) {
    if (keyword.includes(word) && word.length > 2) return 0.8
    if (word.includes(keyword) && keyword.length > 2) return 0.8
    if (levenshtein(word, keyword) <= 2 && keyword.length > 3) return 0.6
  }
  return 0
}

function levenshtein(a, b) {
  const m = a.length, n = b.length
  const dp = Array.from({ length: m + 1 }, (_, i) => Array(n + 1).fill(0))
  for (let i = 0; i <= m; i++) dp[i][0] = i
  for (let j = 0; j <= n; j++) dp[0][j] = j
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      dp[i][j] = a[i-1] === b[j-1]
        ? dp[i-1][j-1]
        : 1 + Math.min(dp[i-1][j], dp[i][j-1], dp[i-1][j-1])
    }
  }
  return dp[m][n]
}

function detectCategory(input) {
  let bestCat = null, bestScore = 0
  for (const [cat, words] of Object.entries(CATEGORIES)) {
    let score = 0
    for (const w of words) {
      if (input.includes(w)) score += 1
    }
    if (score > bestScore) { bestScore = score; bestCat = cat }
  }
  return bestScore > 0 ? bestCat : null
}

