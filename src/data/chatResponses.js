export function getResponse(input) {
  const lower = input.toLowerCase().trim()

  // Exact pill match
  if (RESPONSES[lower] !== undefined) {
    return RESPONSES[lower]
  }

  // Direct keyword match — prefer longest match
  const sorted = Object.entries(KEYWORD_RESPONSES).sort((a, b) => b[0].length - a[0].length)
  for (const [keyword, response] of sorted) {
    if (lower.includes(keyword)) {
      return response
    }
  }

  // Fuzzy keyword match
  let bestMatch = null, bestScore = 0
  for (const [keyword, response] of Object.entries(KEYWORD_RESPONSES)) {
    const score = fuzzyMatch(lower, keyword)
    if (score > bestScore) { bestScore = score; bestMatch = response }
  }
  if (bestScore >= 0.6) return bestMatch

  // Category fallback
  const cat = detectCategory(lower)
  if (cat && CATEGORY_FALLBACKS[cat]) return CATEGORY_FALLBACKS[cat]

  return DEFAULT_RESPONSE
}
